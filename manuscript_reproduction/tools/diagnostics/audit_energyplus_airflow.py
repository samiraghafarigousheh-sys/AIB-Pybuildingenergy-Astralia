"""
Audit the ventilation actually delivered in an EnergyPlus run, hour by hour.

The matched EnergyPlus reference represents the designed ventilation with a
``ZoneVentilation:DesignFlowRate`` object on an always-on schedule, so that air
is exchanged in every hour and not only in the hours an ideal-loads system
operates. This script checks that claim against the SQLite output of the run
instead of against the input file.

It reads, from ``eplusout.sql`` (or ``<tag>out.sql``):

* ``Zone Ventilation Standard Density Volume Flow Rate``  [m3/s]
* ``Schedule Value`` of the ventilation availability schedule (``Always1``)
* ``Zone Ideal Loads Supply Air Sensible Heating/Cooling Energy`` [J]

and reports the flow range, the schedule range, and the number of hours in
which flow is positive while neither sensible heating nor sensible cooling is
delivered (the thermostat deadband).

Scope: this verifies the current reference configuration only. It says nothing
general about ideal-loads systems.

The standard-density flow is normalised to standard air density, so it need
not equal the nominal design flow at every hour.

Usage
-----
    python tools/diagnostics/audit_energyplus_airflow.py path/to/eplusout.sql \
        --output results/submission_review/energyplus/airflow_audit.json
"""

from __future__ import annotations

import argparse
import json
import sqlite3
from pathlib import Path

VAR_FLOW_STD = "Zone Ventilation Standard Density Volume Flow Rate"
VAR_FLOW_CUR = "Zone Ventilation Current Density Volume Flow Rate"
VAR_SCHED = "Schedule Value"
VAR_HEAT = "Zone Ideal Loads Supply Air Sensible Heating Energy"
VAR_COOL = "Zone Ideal Loads Supply Air Sensible Cooling Energy"


def _hourly(cur, name: str, key: str | None = None) -> list[float] | None:
    q = ("SELECT rvd.TimeIndex, SUM(rvd.VariableValue) FROM ReportVariableData rvd "
         "JOIN ReportVariableDataDictionary d "
         "ON rvd.ReportVariableDataDictionaryIndex = d.ReportVariableDataDictionaryIndex "
         "JOIN Time t ON rvd.TimeIndex = t.TimeIndex "
         "WHERE d.VariableName = ? AND d.ReportingFrequency = 'Hourly' "
         "AND (t.EnvironmentPeriodIndex IN (SELECT EnvironmentPeriodIndex "
         "FROM EnvironmentPeriods WHERE EnvironmentType = 3))")
    args: list = [name]
    if key is not None:
        q += " AND UPPER(d.KeyValue) = UPPER(?)"
        args.append(key)
    q += " GROUP BY rvd.TimeIndex ORDER BY rvd.TimeIndex"
    rows = cur.execute(q, args).fetchall()
    return [float(v) for _t, v in rows] if rows else None


def audit_airflow(sql_path: Path | str, schedule: str = "Always1",
                  zero_tol: float = 1e-9) -> dict:
    sql_path = Path(sql_path)
    if not sql_path.is_file():
        raise FileNotFoundError(sql_path)
    con = sqlite3.connect(str(sql_path))
    try:
        cur = con.cursor()
        flow = _hourly(cur, VAR_FLOW_STD)
        if flow is None:
            raise RuntimeError(
                f"'{VAR_FLOW_STD}' is not in {sql_path.name}; re-run the IDF "
                "generated by examples/corrected_vs_energyplus.py, which "
                "requests it")
        flow_cur = _hourly(cur, VAR_FLOW_CUR)
        sched = _hourly(cur, VAR_SCHED, schedule)
        heat = _hourly(cur, VAR_HEAT) or [0.0] * len(flow)
        cool = _hourly(cur, VAR_COOL) or [0.0] * len(flow)
    finally:
        con.close()

    n = len(flow)
    plant_off = [abs(heat[i]) <= zero_tol and abs(cool[i]) <= zero_tol
                 for i in range(n)]
    pos = [f > zero_tol for f in flow]
    out = {
        "sql": str(sql_path),
        "variable": VAR_FLOW_STD,
        "n_hours": n,
        "flow_min_m3_s": min(flow),
        "flow_max_m3_s": max(flow),
        "flow_mean_m3_s": sum(flow) / n,
        "hours_flow_positive": sum(pos),
        "plant_off_hours": sum(plant_off),
        "plant_off_hours_flow_positive": sum(1 for i in range(n)
                                             if plant_off[i] and pos[i]),
        "schedule": schedule,
        "schedule_min": None if sched is None else min(sched),
        "schedule_max": None if sched is None else max(sched),
    }
    if flow_cur is not None:
        out["current_density_flow_mean_m3_s"] = sum(flow_cur) / len(flow_cur)
    out["continuous_ventilation_verified"] = (
        out["hours_flow_positive"] == n
        and (sched is None or out["schedule_min"] >= 1.0 - 1e-9))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sql", type=Path)
    ap.add_argument("--schedule", default="Always1")
    ap.add_argument("--output", type=Path, default=None)
    a = ap.parse_args()
    res = audit_airflow(a.sql, a.schedule)
    txt = json.dumps(res, indent=2)
    if a.output:
        a.output.parent.mkdir(parents=True, exist_ok=True)
        a.output.write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    main()
